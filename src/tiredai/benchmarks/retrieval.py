"""Retrieval benchmark: how well each embedding model, and each way of ranking, finds products for shopper queries.

Two kinds of queries:
- product (benchmarks/retrieval_products.yaml, generated by product_queries): a sampled catalog product
  named the way shoppers write it, in four styles. Relevant products match every field of `relevant`
  (the SKU, or the line and size, or the line). Scored with hit@1, hit@3, hit@10 and reciprocal_rank
  (whose mean is the MRR).
- descriptive (benchmarks/retrieval_descriptive.yaml, hand-written): a need such as "mud tires for my
  jeep". A product's gain is the share of the `relevant` fields it matches. Scored with precision@10
  (products matching all of them) and ndcg@10.

Every query runs without filters through the app's CatalogSearch: with hybrid ranking that is exactly
the agent's search, while dense and sparse rank by one vector alone.
"""

import random
import re
from pathlib import Path
from typing import Literal

import yaml
from langfuse import Evaluation
from pydantic import BaseModel, ConfigDict, Field

from tiredai.benchmarks.catalog import Catalog, gain
from tiredai.benchmarks.experiments import Case, item_value
from tiredai.benchmarks.metrics import hit_at, ndcg_at, precision_at, reciprocal_rank
from tiredai.search import CatalogSearch

DATASET = "tiredai-retrieval"
STYLES = ("full_name", "shopper", "typo", "line_only")
PRODUCT_SCORES = ["hit@1", "hit@3", "hit@10", "reciprocal_rank"]
DESCRIPTIVE_SCORES = ["precision@10", "ndcg@10"]
TOP_K = 10
MIN_DESCRIPTIVE_MATCHES = TOP_K  # so a perfect ranking can reach precision@10 = 1
METRIC_SIZE = re.compile(r"(\d{3})/(\d{2})Z?R(\d{2}(?:\.\d)?)")


class RetrievalQuery(BaseModel):
    model_config = ConfigDict(extra="forbid")

    id: str
    query: str
    relevant: dict[str, list] = Field(min_length=1)  # catalog field (or "line") -> the values that count
    kind: Literal["product", "descriptive"] = "descriptive"
    style: str | None = None
    source_sku: str | None = None  # the product a generated query was made from

    def case(self) -> Case:
        metadata = {"case": self.id, "kind": self.kind, "style": self.style, "source_sku": self.source_sku}
        return Case(
            id=self.id,
            input={"query": self.query},
            expected_output={"relevant": self.relevant},
            metadata={k: v for k, v in metadata.items() if v is not None},
        )


def loose_size(size: str) -> str:
    """'205/55R15' -> '205 55 15', as shoppers often type a size; other sizes are only lowercased."""
    if match := METRIC_SIZE.fullmatch(size):
        return " ".join(match.groups())
    return size.lower()


def with_typo(text: str, rng: random.Random) -> str | None:
    """`text` with one letter dropped from a word of 4+ letters (never its first or last letter); None without one."""
    words = text.split(" ")
    candidates = [i for i, word in enumerate(words) if word.isalpha() and len(word) >= 4]
    if not candidates:
        return None
    i = rng.choice(candidates)
    j = rng.randrange(1, len(words[i]) - 1)
    words[i] = words[i][:j] + words[i][j + 1 :]
    return " ".join(words)


def _quotas(sizes: dict[str, int], total: int) -> dict[str, int]:
    """`total` split in proportion to `sizes` by largest remainder, at least one each and at most the group's size."""
    count = sum(sizes.values())
    exact = {key: total * n / count for key, n in sizes.items()}
    quotas = {key: max(1, int(share)) for key, share in exact.items()}
    for key in sorted(exact, key=lambda k: exact[k] - int(exact[k]), reverse=True):
        if sum(quotas.values()) >= total:
            break
        quotas[key] += 1
    return {key: min(n, sizes[key]) for key, n in quotas.items()}


def product_queries(catalog: Catalog, products: int = 40, seed: int = 7) -> list[RetrievalQuery]:
    """Queries for about `products` products sampled across car types in proportion to their share (at
    least one of each type), in every style.

    - full_name: the catalog name, e.g. "Accelera Phi-R 205/55R15 92V XL" (relevant: that SKU)
    - shopper: lowercase, size typed loosely, no load or speed rating: "accelera phi-r 205 55 15"
      (relevant: same line and size)
    - typo: a letter missing in the line: "acelera phi-r 205/55r15" (relevant: same line and size)
    - line_only: no size: "Accelera Phi-R" (relevant: any size of the line)
    """
    rng = random.Random(seed)
    groups: dict[str, list[dict]] = {}
    for product in sorted(catalog, key=lambda p: p["sku"]):
        if product["line"] != product["name"]:  # the name holds the size, so every style can be written
            groups.setdefault(product.get("carType", "Other"), []).append(product)
    quotas = _quotas({key: len(group) for key, group in groups.items()}, products)
    sampled = [p for key in sorted(groups) for p in rng.sample(groups[key], quotas[key])]

    queries = []
    for product in sampled:
        sku, line, size = product["sku"], product["line"], product["size"]
        same_size = {"line": [line], "size": [size]}
        styles = [("full_name", product["name"], {"sku": [sku]}), ("shopper", f"{line.lower()} {loose_size(size)}", same_size)]
        if typo := with_typo(line, rng):
            styles.append(("typo", f"{typo} {size}".lower(), same_size))
        styles.append(("line_only", line, {"line": [line]}))
        queries += [
            RetrievalQuery(id=f"{sku.lower()}-{style}", kind="product", style=style, query=query, relevant=relevant, source_sku=sku)
            for style, query, relevant in styles
        ]
    return queries


def write_product_queries(path: Path, queries: list[RetrievalQuery], header: str) -> None:
    rows = [q.model_dump(exclude={"kind"}, exclude_none=True) for q in queries]
    path.write_text(f"# {header}\n" + yaml.safe_dump(rows, sort_keys=False, allow_unicode=True, width=200, default_flow_style=None))


def load_queries(products_path: Path, descriptive_path: Path) -> list[RetrievalQuery]:
    queries = [RetrievalQuery(**row, kind="product") for row in yaml.safe_load(products_path.read_text()) or []]
    queries += [RetrievalQuery(**row, kind="descriptive") for row in yaml.safe_load(descriptive_path.read_text()) or []]
    ids = [q.id for q in queries]
    if duplicates := sorted({i for i in ids if ids.count(i) > 1}):
        raise ValueError(f"Duplicate query ids: {', '.join(duplicates)}")
    return queries


def check_queries(queries: list[RetrievalQuery], catalog: Catalog) -> list[str]:
    """What is wrong with the queries given the catalog: unknown fields, or too few relevant products to score."""
    problems = []
    fields = catalog.fields()
    for q in queries:
        if unknown := set(q.relevant) - fields:
            problems.append(f"{q.id}: unknown fields {sorted(unknown)}")
            continue
        matches = sum(gain(p, q.relevant) == 1 for p in catalog)
        needed = 1 if q.kind == "product" else MIN_DESCRIPTIVE_MATCHES
        if matches < needed:
            problems.append(f"{q.id}: {matches} products match all of {q.relevant}, at least {needed} needed")
        if q.source_sku and q.source_sku not in catalog:
            problems.append(f"{q.id}: source SKU {q.source_sku} is not in the catalog")
    return problems


class RankingTask:
    """Runs an item's query through the catalog search and returns the ranking."""

    def __init__(self, search: CatalogSearch):
        self.search = search

    def __call__(self, *, item, **kwargs) -> dict:
        result = self.search.search(query=item_value(item, "input")["query"])
        if "error" in result:
            raise RuntimeError(result["error"])
        products = result["products"]
        return {"ranking": [p["sku"] for p in products], "top3": [p["name"] for p in products[:3]]}


def ranking_evaluator(catalog: Catalog):
    """The item evaluator: product queries get the hit and rank scores, descriptive ones precision and nDCG."""

    def evaluate_ranking(*, output, expected_output, metadata, **kwargs) -> list[Evaluation]:
        relevant = expected_output["relevant"]
        gains = [gain(catalog[sku], relevant) for sku in output["ranking"]]
        full = [g == 1 for g in gains]
        if (metadata or {}).get("kind") == "product":
            first = next((rank for rank, hit in enumerate(full, start=1) if hit), None)
            comment = f"first relevant product at rank {first}" if first else f"no relevant product in the top {len(full)}"
            return [
                Evaluation(name="hit@1", value=hit_at(full, 1), comment=comment),
                Evaluation(name="hit@3", value=hit_at(full, 3), comment=comment),
                Evaluation(name="hit@10", value=hit_at(full, 10), comment=comment),
                Evaluation(name="reciprocal_rank", value=reciprocal_rank(full), comment=comment),
            ]
        best = [gain(p, relevant) for p in catalog]
        comment = f"{sum(full[:TOP_K])} of the top {TOP_K} match all of {relevant}"
        return [
            Evaluation(name="precision@10", value=precision_at(full, TOP_K), comment=comment),
            Evaluation(name="ndcg@10", value=ndcg_at(gains, best, TOP_K), comment=comment),
        ]

    return evaluate_ranking
